import { MAX_TITLE_LENGTH, RESERVED_PROPS } from "./page.js";

/** データの形式の版。ファイルの決まりを読めなくなる形で変えたときだけ上げる */
export const FORMAT_VERSION = 1;

/**
 * プロジェクトのフォルダ直下に置く README.md の中身。
 * アプリが無くても、人や AI がこのフォルダだけを見てデータを読み・作り直せるようにする。
 * サーバーだけが書く（手で直してもアプリが戻す）。型の台帳ができたら、型の一覧もここから書く
 */
export function projectReadme(): string {
  return `---
format: ${FORMAT_VERSION}
---
# このフォルダについて

SABAKAN のデータです。アプリが無くても読めるよう、ふつうの Markdown ファイルだけで書いています。
この README.md はアプリが自動で書き直します（手で直しても戻ります）。

## フォルダ

- \`pages/\`：1 ページ = 1 つの \`.md\` ファイル。ファイル名（\`.md\` を除く）がページの題名。フォルダは作らない
- \`assets/\`：ページに貼った画像
- \`README.md\`：このファイル

## ページの形

\`\`\`markdown
---
id: 01JD3Z8Q5N0000000000000000
type: book
tags: [読書]
created_at: 2026-11-15T17:00:00+09:00
author: "[[山田]]"
rating: 4
---
本文（Markdown）。[[別のページ]] へのリンクや #タグ が書ける
\`\`\`

- 先頭の \`---\` で囲んだ部分（frontmatter、YAML）がページの項目。無くてもよい
- 予約された項目は ${RESERVED_PROPS.map((k) => `\`${k}\``).join("・")} の ${RESERVED_PROPS.length} つ
  - \`id\`：ページの変わらない番号（ULID、26 文字。先頭 10 文字が作った時刻）。題名を変えても変わらない。外からページを指すときに使う。古いページなどには無いこともある
  - \`type\`：ページの種類（例：\`book\`）。無ければふつうのページ
  - \`tags\`：タグのリスト。本文の \`#タグ\` と同じ扱い
  - \`created_at\`：作った日時（日本時間）。古いページには無い
- 項目の並びは、予約された項目が先、残りは名前順
- 値は「文字・数・真偽（true / false）、またはそのリスト」だけ。入れ子は使わない
- 日付は \`YYYY-MM-DD\`、日時は \`YYYY-MM-DDTHH:mm:ss+09:00\`、金額は円の整数
- 数字だけの文字（郵便番号など）は引用符で囲む（例：\`zip: "0123456"\`）

## リンクとタグ

- \`[[題名]]\`：その題名のページへのリンク。\`[[題名|表示名]]\` とも書ける。項目の値に書くときは引用符で囲む（\`author: "[[山田]]"\`）
- \`#タグ\`：行頭か空白の後の \`#\` から空白まで
- 題名の比べ方：Unicode の NFC にそろえ、空白と \`_\` を同じとみなし、大文字小文字を区別しない
- 題名は ${MAX_TITLE_LENGTH} 文字まで。ファイル名に使えない文字（\`\\ / : * ? " < > |\`）は全角の「－」に置き換える

## 一覧（query ブロック）

本文に次のように書くと、条件に合うページの一覧になる。

\`\`\`\`markdown
\`\`\`query
where: type = book
sort: rating desc
group: status
view: table
\`\`\`
\`\`\`\`

## アプリの外から触るとき

- 読む・中身を直すのは、このフォルダのファイルを直接触ってよい
- 新しいファイルは、アプリから作る（アプリは自分で作ったファイルしか見えない。外で作ったファイルや複製は、アプリには出てこない）
- 題名を変えるときはアプリから（ほかのページのリンクも書き換える）
- \`id\` を書き換えたり消したりしない
`;
}
